-- ----------------------------------------------------------------------------
-- Prove it at apply time. Fails the migration if any table is not readable by
-- `authenticated` -- the exact condition that makes a rebuild useless.
-- ----------------------------------------------------------------------------
do $$
declare v_missing text;
begin
  select string_agg(c.relname, ', ' order by c.relname) into v_missing
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r'
    and not has_table_privilege('authenticated', c.oid, 'SELECT');
  if v_missing is not null then
    raise exception 'tables not readable by authenticated after explicit grants: %', v_missing;
  end if;
  raise notice 'explicit grants applied; all % tables readable by authenticated',
    (select count(*) from pg_class c join pg_namespace n on n.oid=c.relnamespace
     where n.nspname='public' and c.relkind='r');
end $$;

